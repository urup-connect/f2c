# Storefronts
# https://design/verticals.md section 8

def _storefront_hosts(raw):
    """``host=storefront,host=storefront`` into a mapping. Blank is no mapping.

    A mapping rather than a table: the hosts a deployment answers on are already
    environment configuration -- ALLOWED_HOSTS and CSRF_TRUSTED_ORIGINS above --
    and adding a QA domain should not need a migration. See
    ``app.core.storefronts.resolution``.
    """
    pairs = {}
    for entry in (raw or '').split(','):
        entry = entry.strip()
        if not entry or '=' not in entry:
            continue
        host, _, storefront = entry.partition('=')
        host = host.strip().lower()
        storefront = storefront.strip().lower()
        if host and storefront:
            pairs[host] = storefront
    return pairs


# These are the hosts *Django* answers on, not the ones the browser shows. The
# frontend's name never reaches here; `request.get_host()` is the API host. So the
# production mapping is:
#
#   DJANGO_STOREFRONT_HOSTS=backend.f2c.co.za=market,backend.f2c-cannabis.co.za=club

def _mailer(prefix, storefront):
    """One SMTP mailer from the ``EMAIL_<prefix>_*`` variables.

    **A blank host is fatal outside local development.** It would otherwise fall
    back to some other storefront's server, and that failure is quiet in the
    worst way: the mail sends, so nothing looks wrong, and the store's members
    receive a club-signed email from a provider that has no business holding
    their address. The same call `payfast_config` makes about a sandbox merchant.

    Locally a blank host means the console backend, so the whole flow -- sign-in
    codes included -- works with no mail server at all.
    """
    host = (os.environ.get(f'EMAIL_{prefix}_HOST') or '').strip()
    if not host:
        if not DEBUG:
            raise ImproperlyConfigured(
                f'EMAIL_{prefix}_HOST is not set. It is the SMTP server the '
                f'{storefront} storefront sends from, and there is deliberately '
                "no fallback: sending one storefront's mail through another's "
                'server succeeds silently and is wrong.'
            )
        return {'BACKEND': 'django.core.mail.backends.console.EmailBackend'}

    # TLS unless SSL is asked for, and defaulted *on*: a password crossing the
    # network in cleartext is not something to arrive at by leaving a variable
    # blank. Implicit SSL on 465 is common with South African providers, which
    # is why both spellings exist.
    use_ssl = env_bool(f'EMAIL_{prefix}_USE_SSL', default=False)
    use_tls = env_bool(f'EMAIL_{prefix}_USE_TLS', default=not use_ssl)
    if use_tls and use_ssl:
        raise ImproperlyConfigured(
            f'EMAIL_{prefix}_USE_TLS and EMAIL_{prefix}_USE_SSL are mutually '
            f'exclusive. STARTTLS on 587 is EMAIL_{prefix}_USE_TLS; implicit '
            f'TLS on 465 is EMAIL_{prefix}_USE_SSL.'
        )

    raw_port = (os.environ.get(f'EMAIL_{prefix}_PORT') or '').strip()
    try:
        port = int(raw_port) if raw_port else (465 if use_ssl else 587)
    except ValueError:
        raise ImproperlyConfigured(
            f'EMAIL_{prefix}_PORT must be a whole number, not {raw_port!r}.'
        ) from None

    return {
        'BACKEND': 'django.core.mail.backends.smtp.EmailBackend',
        'OPTIONS': {
            'host': host,
            'port': port,
            'username': (os.environ.get(f'EMAIL_{prefix}_USER') or '').strip(),
            'password': os.environ.get(f'EMAIL_{prefix}_PASSWORD') or '',
            'use_tls': use_tls,
            'use_ssl': use_ssl,
            # Bounded, because this send happens in a worker thread the sign-in
            # request is waiting on. An unreachable mail server must fail rather
            # than hold the thread until the client gives up.
            'timeout': 10,
        },
    }


def _from_email(prefix, storefront):
    """The address one storefront's mail is sent as.

    Not a `MAILERS` key -- Django has none -- so it is read here and applied by
    `storefronts.mail`. Required outside local development for the same reason
    the host is: most providers reject a `From` they do not own, and the two
    storefronts are on different domains, so one shared sender address cannot be
    right for both.
    """
    value = (os.environ.get(f'EMAIL_{prefix}_FROM') or '').strip()
    if value:
        return value
    if not DEBUG:
        raise ImproperlyConfigured(
            f'EMAIL_{prefix}_FROM is not set. It is the address the '
            f'{storefront} storefront sends as, e.g. no-reply@example.co.za, '
            'and it normally has to be one the provider above is authorised to '
            'send for.'
        )
    return DEFAULT_FROM_EMAIL



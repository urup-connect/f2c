# **Two SMTP servers, and the split is by storefront rather than by message.**
# The club and the produce market are separate businesses on separate registrable
# domains, and each has its own mailbox provider. Club mail leaves the club's
# server (`EMAIL_CC_*`), market mail leaves the store's (`EMAIL_F2C_*`), and that
# includes the sign-in code -- a store customer must not receive a club-branded
# email from a club domain, and the club's provider would refuse to send it as
# the store anyway.
#
# The aliases are the storefront codes themselves, so routing is
# `.send(using=storefront)` with nothing to look up. That is the same shape as
# `WEBAUTHN_RP_IDS` above and for the same reason -- see
# `app.core.storefronts.mail`, which is the one place a caller asks.
#
# The literals are spelled out rather than imported from `Storefront`: this file
# is loaded to *build* the app registry, so it cannot import a models module.
# `storefronts.checks` asserts the two agree, which is what keeps the duplication
# honest.

# The address OTP emails are sent from when a storefront names none of its own.
# Django's default is 'webmaster@localhost'.

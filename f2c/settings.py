# Throttling
# https://django-ninja.dev/guides/throttling/

# Scopes referenced by the throttle classes in authn/throttles.py. Rates are
# per client IP; the OTP send rate is the one that stops the API being used to
# mailbomb a member.
NINJA_DEFAULT_THROTTLE_RATES = {
    'auth_start': '20/m',
    'otp_start': '5/m',
    'otp_verify': '10/m',
    'passkey_verify': '20/m',
    # Tighter than the rest on purpose: a person joins a club once, and
    # nothing legitimate registers twice in a minute. See
    # membership/throttles.py -- this is the control that stands in for the
    # CSRF check an unauthenticated, server-to-server endpoint cannot have.
    'register': '5/m',
    # Creating a store account. The same shape and the same job as `register`
    # above, and a scope of its own so the two can be tuned apart: one
    # storefront is a club somebody joins once and the other is a shop. Held at
    # the same rate because a registration also emails a sign-in code, so the
    # limit bounds mail to a typed address as well as rows in the table. See
    # accounts/throttles.py.
    'customer_register': '5/m',
    # The nickname check the sign-up form makes when the field loses focus.
    # Looser than `register`: a member tries a few names in one sitting, and
    # each one is a request. See membership/throttles.py.
    'nickname_availability': '30/m',
    # Reading a checkout. Generous, because it is read again every time a
    # member returns to an abandoned Payfast page, and the control that
    # actually bounds token guessing is the 32 bytes of entropy in the
    # token. See payments/throttles.py -- and note that the Payfast
    # notification endpoint is deliberately not listed here at all.
    'checkout': '30/m',
    # Uploading an avatar. Keyed on the account rather than the IP, which is
    # what the rest of this list cannot do -- these endpoints need a session.
    # Tight because each request decodes and re-encodes an image up to 8MB,
    # which is the most expensive thing a member can ask this API to do, and
    # nothing legitimate replaces a photograph ten times a minute. See
    # accounts/throttles.py.
    'avatar_upload': '10/m',
    # Writing the three editable profile fields. Cheap, but a member editing
    # their own record has no reason to save it thirty times a minute either.
    'profile_write': '20/m',
}


